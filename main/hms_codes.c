const char *hms_lookup(uint32_t code, char *buf, size_t n)
{
    for (size_t i = 0; i < sizeof(HMS_TABLE) / sizeof(HMS_TABLE[0]); i++) {
        if (HMS_TABLE[i].code == code) return HMS_TABLE[i].text;
    }
    snprintf(buf, n, "HMS %08X", (unsigned)code);
    return buf;
}
